package org.openbw.androidtest;

import java.io.*;
import java.nio.file.*;
import java.util.*;
import java.util.zip.*;
import org.json.*;

/** Test the real optional-interface import allowlist with owned campaign archives. */
public final class ReplayAssets81Test {
  static Set<String> entries(File zip) throws Exception {
    try (ZipFile z = new ZipFile(zip)) {
      JSONObject manifest = new JSONObject(new String(z.getInputStream(z.getEntry("manifest.json")).readAllBytes(), "UTF-8"));
      Set<String> result = new HashSet<String>(); JSONArray values = manifest.getJSONArray("entries");
      for (int i=0;i<values.length();i++) result.add(values.getJSONObject(i).getString("name"));
      return result;
    }
  }
  public static void main(String[] args) throws Exception {
    File root = new File(args[0]), out = new File(args[1]); out.mkdirs();
    for (String game : new String[]{"StarCraft","BroodWar"}) {
      File folder = new File(out,game);folder.mkdirs();
      File bundle = new File(folder, InterfaceData.NAME);
      try (FileInputStream in = new FileInputStream(new File(root,game+".mpq"))) {
        InterfaceData.importArchive(in.getChannel(),folder,p->{});
      }
      InterfaceData.validate(bundle);
      Set<String> names = entries(bundle);
      for (String name : new String[]{"rez\\gluload.bin","glue\\load\\plist.pcx","glue\\load\\pinfo.pcx"})
        if (!names.contains(name)) throw new AssertionError("Missing replay UI import: "+game+" "+name);
      File compact = NativeData.prepare(bundle,folder,"interface");
      System.out.println(game+" "+compact.getAbsolutePath());
      // A bundle generated by build 80 must still pass with optional new UI absent.
      File legacy = new File(folder,"legacy.zip");
      try (ZipFile source = new ZipFile(bundle); ZipOutputStream dest = new ZipOutputStream(new FileOutputStream(legacy))) {
        for (ZipEntry entry : Collections.list(source.entries())) {
          byte[] bytes = source.getInputStream(entry).readAllBytes();
          if (entry.getName().equals("manifest.json")) {
            JSONObject manifest = new JSONObject(new String(bytes,"UTF-8"));
            JSONArray values = manifest.getJSONArray("entries");
            for (int i=values.length()-1;i>=0;i--) {
              String name = values.getJSONObject(i).getString("name");
              if (name.equals("rez\\gluload.bin") || name.startsWith("glue\\load\\")) values.remove(i);
            }
            bytes = manifest.toString().getBytes("UTF-8");
          }
          dest.putNextEntry(new ZipEntry(entry.getName()));dest.write(bytes);dest.closeEntry();
        }
      }
      InterfaceData.validate(legacy);
    }
  }
}
